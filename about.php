<section class="card glass" id="brand">
    <h2>Brand Identity</h2>
    <p>
        The name ABEKa gives the platform a distinct identity that users can recognize and associate with Pampanga. The name is presented in a clear, memorable form so that it remains easy to identify while representing a platform created for the province and its people.
    </p>
    <p>
        The ABEKa logo represents the Province of Pampanga as a whole. Its lettering is inspired by Kulitan, the traditional writing system of the Kapampangan people. Although the design draws from this cultural script, it is arranged so that the name ABEKa can still be read and recognized. This brings together a part of Pampanga's cultural heritage and the identity of a modern digital platform.
    </p>
    <p>
        The illustrated background of the logo represents major sectors that contribute to Pampanga's economy and development. Agricultural elements recognize the importance of farming and the province's agricultural communities. The industrial elements reflect the growth of its cities and the role of industry in creating livelihoods and economic opportunities. The fishery elements acknowledge fishing and aquatic resources as another important source of livelihood. Together, these images represent the different communities and industries that help shape Pampanga.
    </p>
    <p>
        The colors used in the logo and website also help express the character of ABEKa. Green is prominent in the design and can represent the province's natural resources, agricultural land, growth, and continued development. Blue suggests trust, stability, and connection, while also bringing to mind water and the province's fishing communities. Yellow and orange add warmth, optimism, and energy. They can also suggest sunlight, harvest, opportunity, and the active spirit of local communities. The light background gives the interface an open, calm, and welcoming feel, helping the brighter colors and illustrated elements stand out without making the website difficult to view. Together, these colors create a friendly identity that connects ABEKa with Pampanga's natural resources, economic activity, and people.
    </p>
</section>

